        private static string PadBuffer(string buffer)
        {
            int blockSize = 16;
            int paddingSize = blockSize - (buffer.Length % blockSize);
            return buffer + new string((char)paddingSize, paddingSize);
        }

        private static string UnpadBuffer(string input)
        {
            if (string.IsNullOrEmpty(input)) return string.Empty;
            int padLen = input[input.Length - 1];
            if (padLen <= 0 || padLen > 16) return string.Empty;
            for (int i = 0; i < padLen; i++)
                if (input[input.Length - 1 - i] != padLen) return string.Empty;
            return input.Substring(0, input.Length - padLen);
        }

        public string Encrypt(string buffer)
        {
            if (string.IsNullOrEmpty(buffer)) return string.Empty;

            buffer = PadBuffer(buffer);

            Random rnd = new Random();
            int keyIndex = rnd.Next(0, m_vAESKeys.Count);
            byte[] key = m_vAESKeys[keyIndex];
            byte[] iv = m_vAESIVs[keyIndex];

            using (Aes aes = Aes.Create())
            {
                aes.KeySize = 256;
                aes.Mode = CipherMode.CBC;
                aes.Padding = PaddingMode.None;
                aes.Key = key;
                aes.IV = iv;

                ICryptoTransform encryptor = aes.CreateEncryptor();
                byte[] plainBytes = Encoding.UTF8.GetBytes(buffer);
                byte[] cipherBytes = encryptor.TransformFinalBlock(plainBytes, 0, plainBytes.Length);

                byte[] result = new byte[cipherBytes.Length + 1];
                result[0] = (byte)(keyIndex + 31);
                Array.Copy(cipherBytes, 0, result, 1, cipherBytes.Length);
                return Encoding.UTF8.GetString(result);
            }
        }

        public string Decrypt(byte[] encryptedBytes)
        {
            if (encryptedBytes == null || encryptedBytes.Length == 0) return string.Empty;


            byte keyIndex = (byte)(encryptedBytes[0] - 31);
            if (keyIndex >= m_vAESKeys.Count || keyIndex >= m_vAESIVs.Count) return string.Empty;


            byte[] key = m_vAESKeys[keyIndex];
            byte[] iv = m_vAESIVs[keyIndex];
            byte[] cipherBytes = new byte[encryptedBytes.Length - 1];
            Array.Copy(encryptedBytes, 1, cipherBytes, 0, cipherBytes.Length);


            using (Aes aes = Aes.Create())
            {
                aes.KeySize = 256;
                aes.Mode = CipherMode.CBC;
                aes.Padding = PaddingMode.None;
                aes.Key = key;
                aes.IV = iv;


                ICryptoTransform decryptor = aes.CreateDecryptor();
                byte[] plainBytes = decryptor.TransformFinalBlock(cipherBytes, 0, cipherBytes.Length);


                string plaintext = Encoding.UTF8.GetString(plainBytes);
                return UnpadBuffer(plaintext);
            }
        }


        public string GetMD5Hash(string data)
        {
            using (MD5 md5 = MD5.Create())
            {
                byte[] hashBytes = md5.ComputeHash(Encoding.UTF8.GetBytes(data));
                StringBuilder sb = new StringBuilder();
                foreach (byte b in hashBytes)
                    sb.Append(b.ToString("x2"));
                return sb.ToString();
            }
